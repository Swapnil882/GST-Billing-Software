import asyncio
import datetime
from pathlib import Path
from backend.app.config import DATA_DIR, PROFILE_PATH, META_PATH
from backend.app.core.storage import read_all_from_dir, read_json, write_json_atomic
from backend.app.core.path_guard import safe_file_name
from backend.app.core.logging_util import log_error
from backend.app.services.invoice_math import (
    business_key_of,
    get_next_invoice_number,
    advance_date
)

def local_today() -> str:
    """Return local current date as YYYY-MM-DD."""
    return datetime.date.today().isoformat()

def template_is_active(tpl: dict) -> bool:
    return tpl.get('active') is not False

def template_has_ended(tpl: dict, today: str) -> bool:
    end_mode = tpl.get('endMode')
    if end_mode == 'onDate' and tpl.get('endDate'):
        return today > tpl['endDate']
    if end_mode == 'afterN' and tpl.get('maxOccurrences'):
        return int(tpl.get('occurrencesCreated') or 0) >= int(tpl['maxOccurrences'])
    return False

def generate_from_template(tpl: dict, today: str) -> str:
    """Generate a single bill from recurring template and advance schedule."""
    profiles = read_all_from_dir('profiles')
    profile = None
    if tpl.get('ownerGstin'):
        profile = next((p for p in profiles if p.get('gstin') == tpl['ownerGstin']), None)
    if not profile and tpl.get('profileId'):
        profile = next((p for p in profiles if p.get('id') == tpl['profileId']), None)
    if not profile and (tpl.get('profileBusinessName') or tpl.get('ownerName')):
        name = tpl.get('profileBusinessName') or tpl.get('ownerName')
        profile = next((p for p in profiles if p.get('businessName') == name), None)
    if not profile:
        profile = read_json(PROFILE_PATH, {})
        
    inv_type = tpl.get('invoiceType') or 'tax-invoice'
    prefix_map = {
        'proforma': 'EST',
        'quotation': 'QUO',
        'credit-note': 'CN',
        'bill-of-supply': 'BOS',
        'composition': 'COMP',
        'delivery-challan': 'DC',
    }
    prefix = prefix_map.get(inv_type, 'INV')
    
    biz_key = business_key_of(profile)
    invoice_number = get_next_invoice_number(prefix, inv_type, biz_key)
    # Check for collision
    bills_dir = DATA_DIR / 'bills'
    for _ in range(50):
        if not (bills_dir / f"{safe_file_name(invoice_number)}.json").exists():
            break
        invoice_number = get_next_invoice_number(prefix, inv_type, biz_key)
        
    invoice_date = today
    due_days = tpl.get('dueDays')
    due_date = ''
    try:
        if due_days is not None and due_days != '':
            d_days = int(due_days)
            if d_days >= 0:
                parts = [int(p) for p in invoice_date.split('-')[:3]]
                curr = datetime.date(parts[0], parts[1], parts[2])
                due_date = (curr + datetime.timedelta(days=d_days)).isoformat()
    except Exception:
        due_date = ''
        
    # Calculate simple totals or use template values
    total_amount = float(tpl.get('totalAmount') or tpl.get('total') or 0.0)
    tax_total = float(tpl.get('totalTaxAmount') or tpl.get('totalTax') or 0.0)
    
    bill = {
        "id": invoice_number,
        "clientName": tpl.get("clientName", ""),
        "invoiceNumber": invoice_number,
        "invoiceDate": invoice_date,
        "invoiceType": inv_type,
        "currency": (tpl.get("invoiceOptions") or {}).get("currency") or "INR",
        "totalAmount": total_amount,
        "totalTaxAmount": tax_total,
        "status": "unpaid",
        "paidAmount": 0,
        "payments": [],
        "generatedFrom": tpl.get("id"),
        "autoGenerated": True,
        "autoGeneratedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "data": {
            "profile": profile,
            "client": {
                "name": tpl.get("clientName", ""),
                "state": tpl.get("clientState", ""),
                "gstin": tpl.get("clientGstin", ""),
                "address": tpl.get("clientAddress", ""),
                "country": tpl.get("clientCountry", ""),
                "city": tpl.get("clientCity", ""),
                "pin": tpl.get("clientPin", ""),
                "email": tpl.get("clientEmail", ""),
                "phone": tpl.get("clientPhone", ""),
                "isSEZ": tpl.get("isSEZ", False),
            },
            "details": {
                "invoiceNumber": invoice_number,
                "invoiceDate": invoice_date,
                "dueDate": due_date,
                "placeOfSupply": tpl.get("placeOfSupply", "")
            },
            "items": [
                {**item, "name": item.get("name") or item.get("description", "")}
                for item in tpl.get("items", [])
            ],
            "totals": tpl.get("totals", {}),
            "invoiceType": inv_type,
            "customTerms": tpl.get("customTerms", ""),
            "customNotes": tpl.get("customNotes", ""),
            "extraSections": tpl.get("extraSections", []),
            "invoiceOptions": tpl.get("invoiceOptions", {}),
            "taxInclusive": bool(tpl.get("taxInclusive")),
        }
    }
    
    write_json_atomic(bills_dir / f"{safe_file_name(invoice_number)}.json", bill)
    
    # Advance schedule
    from_date = tpl.get("nextDate") or today
    anchor_day = tpl.get("anchorDay")
    if not anchor_day and tpl.get("frequency") != "weekly":
        try:
            anchor_day = int(from_date.split('-')[2])
            tpl["anchorDay"] = anchor_day
        except Exception:
            pass
            
    tpl["nextDate"] = advance_date(from_date, tpl.get("frequency", "monthly"), tpl.get("interval", 1), anchor_day)
    tpl["lastGenerated"] = today
    tpl["occurrencesCreated"] = int(tpl.get("occurrencesCreated") or 0) + 1
    
    write_json_atomic(DATA_DIR / "recurring" / f"{safe_file_name(tpl.get('id'))}.json", tpl)
    return invoice_number

async def process_due_recurring():
    """Scan recurring templates and fire any due bills."""
    today = local_today()
    templates = read_all_from_dir('recurring')
    fired = 0
    for tpl in templates:
        await asyncio.sleep(0) # yield
        if not tpl or not template_is_active(tpl):
            continue
        next_date = tpl.get("nextDate")
        if not next_date or next_date > today:
            continue
        if template_has_ended(tpl, today):
            continue
        try:
            generate_from_template(tpl, today)
            fired += 1
        except Exception as e:
            log_error(f"Error processing recurring template {tpl.get('id')}: {e}", "recurring")
            
    if fired > 0:
        meta = read_json(META_PATH, {})
        meta["lastRecurringAutoFire"] = {
            "date": today,
            "count": fired,
            "at": datetime.datetime.now(datetime.timezone.utc).isoformat()
        }
        write_json_atomic(META_PATH, meta)
